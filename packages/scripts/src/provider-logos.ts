import { resolve } from "node:path"

import { capture } from "@/capture"
import { fetchOk } from "@/fetch-ok"

// Copies each provider's logo from models.dev into a generated module of Remix-style components, drawn in the text color so they follow the theme; run with `bun run provider:logos`.

const ROOT = resolve(import.meta.dir, "../../..")
const OUT = resolve(ROOT, "web/next/src/components/common/provider-logos.tsx")

// Provider IDs as models.dev and an agent's model write them, the part before the slash.
export const PROVIDERS = ["anthropic", "zai"]

export const MODELS_DEV = "https://raw.githubusercontent.com/anomalyco/models.dev/dev/providers"

export type Logo = { body: string; viewBox: string }

const PAINT = ["fill", "stroke", "stroke-linecap", "stroke-linejoin", "stroke-width"]

const jsxName = (name: string) => name.replace(/[-:]([a-z])/g, (_, c: string) => c.toUpperCase())

// A logo's viewBox and inner markup as JSX, its root's paint carried on a group; fails on a logo that would not follow the text color or that could run code.
export function toLogo(svg: string, provider: string): Logo {
  const root = svg.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/)
  if (!root) throw new Error(`${provider}: no <svg> root`)
  const [, attributes = "", inner = ""] = root
  const viewBox = attributes.match(/\bviewBox="([^"]+)"/)?.[1]
  if (!viewBox) throw new Error(`${provider}: no viewBox`)
  if (/<(a|foreignObject|image|script|style|use)\b|\son\w+=|\sstyle=|href=/i.test(inner))
    throw new Error(`${provider}: markup other than shapes`)
  const colors = [...svg.matchAll(/\s(?:fill|stroke)="([^"]*)"/g)]
    .map((m) => m[1])
    .filter((paint) => paint !== "currentColor" && paint !== "none")
  if (colors.length)
    throw new Error(`${provider}: painted in ${colors.join(", ")}, not currentColor`)
  const body = inner
    .replace(/<!--[\s\S]*?-->|<title>[\s\S]*?<\/title>/g, "")
    .trim()
    .replace(/\s([a-z]+(?:[-:][a-z]+)+)=/g, (_, name: string) => ` ${jsxName(name)}=`)
  const paint = PAINT.flatMap((name) => {
    const value = attributes.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1]
    return value === undefined ? [] : [`${jsxName(name)}="${value}"`]
  })
  return { body: paint.length ? `<g ${paint.join(" ")}>${body}</g>` : body, viewBox }
}

// A provider's component name: its ID in PascalCase, as in zai to Zai.
export const componentName = (provider: string) =>
  provider.replace(/(^|[-.])([a-z0-9])/g, (_, _separator, c: string) => c.toUpperCase())

// The generated module: one component per provider, A to Z, typed and sized like a Remix icon.
export function render(logos: Record<string, Logo>): string {
  const components = Object.keys(logos)
    .sort()
    .map((provider) => {
      const { body, viewBox } = logos[provider]!
      return `export const ${componentName(provider)}: RemixiconComponentType = ({ color = "currentColor", size = 24, ...props }) => (
  <svg xmlns="http://www.w3.org/2000/svg" viewBox=${JSON.stringify(viewBox)} width={size} height={size} color={color} fill={color} {...props}>
    ${body}
  </svg>
)`
    })
  return `// Generated by \`bun run provider:logos\` from models.dev; change the providers in packages/scripts/src/provider-logos.ts, not here.
import type { RemixiconComponentType } from "@remixicon/react"

${components.join("\n\n")}
`
}

// The whole run: fetch every provider's logo from base, and write the formatted module to out only when all of them read.
export async function generate(options: { base: string; out: string; providers: string[] }) {
  const { base, out, providers } = options
  const logos = Object.fromEntries(
    await Promise.all(
      providers.map(async (provider) => {
        const svg = await (await fetchOk(`${base}/${provider}/logo.svg`)).text()
        return [provider, toLogo(svg, provider)] as const
      }),
    ),
  )
  const formatted = await capture(["bunx", "oxfmt", "--stdin-filepath", OUT], ROOT, render(logos))
  await Bun.write(out, formatted)
  return Object.keys(logos).sort()
}

if (import.meta.main) {
  const written = await generate({ base: MODELS_DEV, out: OUT, providers: PROVIDERS })
  console.log(`${written.join(", ")}\n\nWrote ${OUT}`)
}
