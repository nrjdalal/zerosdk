import { resolve } from "node:path"

import type { SourceFile } from "typescript/unstable/ast"
import { API, type Checker, type Project, type Symbol, type Type } from "typescript/unstable/async"

import { compile, jsdoc, printType, SCHEMAS, type SchemaName } from "@/schema-sources"

// Prints each schema in packages/schema as the TypeScript type its records are written as, its fields grouped and ordered as the schema lays them out, and writes it into the schema's docs page; run with `bun run schema:types` after changing a schema.

const ROOT = resolve(import.meta.dir, "../../..")

// The schemas with a docs page, the ones the sources are compared for, by file name; each file exports its schema under the name capitalized.
export const NAMES = Object.keys(SCHEMAS) as SchemaName[]

export const locate = (name: SchemaName) => ({
  out: resolve(ROOT, `web/next/src/schemas/${name}.type.mdx`),
  schema: resolve(ROOT, `packages/schema/src/${name}.ts`),
  type: `${name[0]!.toUpperCase()}${name.slice(1)}`,
})

// group is the comment above a field that opens one of the schema's groups.
type Field = {
  description: string
  fields?: Field[]
  group?: string
  name: string
  optional: boolean
  type: string
}

// The compiler sorts a union's members, while a schema lists an enum's in the order it means, such as effort from low to max, so members found in the field's source keep its order.
export const inSourceOrder = (type: string, source: string) => {
  const parts = type.split(" | ")
  if (!parts.every((p) => source.includes(p))) return type
  return parts.sort((a, b) => source.indexOf(a) - source.indexOf(b)).join(" | ")
}

const members = (fields: Field[], indent: string): string =>
  fields
    .map(
      (f) =>
        `${f.group ? `${indent}// ${f.group}\n` : ""}${jsdoc(f.description, indent)}${indent}${f.name}${f.optional ? "?" : ""}: ${f.fields ? `{\n${members(f.fields, `${indent}  `)}${indent}}` : f.type}\n`,
    )
    .join("")

// Zod names the type of z.json() JSONType, which a block on its own cannot resolve, so a block that prints it declares it above the cut.
const JSON_TYPE =
  "type JSONType = string | number | boolean | null | JSONType[] | { [key: string]: JSONType }\n// ---cut---\n"

export const render = (name: SchemaName, description: string, fields: Field[]) => {
  const body = members(fields, "  ")
  return `{/* Generated by \`bun run schema:types\`; edit packages/schema/src/${name}.ts, not this file. */}\n\n\`\`\`ts twoslash title="@packages/schema/${name}"\n${body.includes("JSONType") ? JSON_TYPE : ""}${jsdoc(description)}export type ${locate(name).type} = {\n${body}}\n\`\`\`\n`
}

// Each property of type as a field, in the order the schema declares them; one whose type is an object is printed as a block of its own fields.
async function fieldsOf(checker: Checker, project: Project, type: Type): Promise<Field[]> {
  const field = async (symbol: Symbol) => {
    const node = (await symbol.declarations![0]!.resolve(project))!
    const file = node.getSourceFile()
    const { optional, type: printed } = await printType(checker, symbol)
    const group = file.text
      .slice(node.pos, node.getStart(file))
      .match(/^\s*\/\/ (metadata|optional|required)$/m)?.[1]
    const object = printed.startsWith("{")
      ? await checker.getNonNullableType((await checker.getTypeOfSymbol(symbol))!)
      : undefined
    const read: Field = {
      description: await symbol.getDocumentationComment(checker),
      ...(object && { fields: await fieldsOf(checker, project, object) }),
      group,
      name: symbol.name,
      optional,
      type: inSourceOrder(printed, node.getText(file)),
    }
    return [node.pos, read] as const
  }
  const fields = await Promise.all((await checker.getPropertiesOfType(type)).map(field))
  return fields.sort(([a], [b]) => a - b).map(([, f]) => f)
}

// Reads the schema through TypeScript's compiler API, from a file in cache that names its input type, and returns the formatted docs block.
export async function generate(options: { cache: string; name: SchemaName }): Promise<string> {
  const { cache, name } = options
  const { schema: path, type } = locate(name)
  const api = new API({ cwd: cache })
  try {
    const { project, sourceFiles } = await compile({ api, cache }, name, [
      // z.input spelled out, since zod resolves only from the schema package.
      `import type { ${type} } from "${path}"\nexport type Target = (typeof ${type})["_zod"]["input"]\n`,
    ])
    const checker = project.checker
    const exported = async (file: SourceFile | undefined, symbol: string) =>
      (await checker.getExportsOfModule((await checker.getSymbolAtLocation(file!))!)).find(
        (e) => e.name === symbol,
      )!
    const schema = await exported(await project.program.getSourceFile(path), type)
    const target = await exported(sourceFiles[0], "Target")
    const fields = await fieldsOf(
      checker,
      project,
      (await checker.getDeclaredTypeOfSymbol(target))!,
    )
    // Left unformatted, as .oxfmtrc.jsonc leaves these files, so each field stays on one line as the schema keeps it.
    return render(name, await schema.getDocumentationComment(checker), fields)
  } finally {
    await api.close()
  }
}

